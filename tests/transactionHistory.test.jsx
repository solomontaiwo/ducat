import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import TransactionList from '../src/components/Transaction/TransactionList.jsx';
const mocks = vi.hoisted(() => ({ user:{uid:'owner'}, transactions:[], revision:0, fetch:vi.fn(), all:vi.fn(), count:vi.fn(), t:(key,options)=>options?.returnObjects?[]:key }));
vi.mock('../src/components/Layout/HeaderProfileButton.jsx',()=>({default:()=>null}));
vi.mock('../src/context/AuthProvider.jsx',()=>({useAuth:()=>({currentUser:mocks.user,loading:false})}));
vi.mock('../src/context/UnifiedTransactionProvider.jsx',()=>({useUnifiedTransactions:()=>({transactions:mocks.transactions,isDemo:false,fetchTransactionPage:mocks.fetch,fetchAllTransactions:mocks.all,getTotalTransactionCount:mocks.count,recentRevision:mocks.revision})}));
vi.mock('react-responsive',()=>({useMediaQuery:()=>true}));
vi.mock('react-i18next',()=>({useTranslation:()=>({t:mocks.t,i18n:{language:'it'}})}));
vi.mock('../src/components/Transaction/TransactionModal.jsx',()=>({default:()=>null}));
const item=(id)=>({id,description:id,date:new Date(),amount:5,category:'altro',type:'expense'});
beforeEach(()=>{vi.clearAllMocks();mocks.user={uid:'owner'};mocks.transactions=[];mocks.revision=0;mocks.count.mockResolvedValue(1);mocks.fetch.mockResolvedValue({items:[item('rent-old')],nextCursor:null,hasMore:false});vi.stubGlobal('IntersectionObserver',class{observe(){}unobserve(){}});});
afterEach(()=>{cleanup();vi.unstubAllGlobals();});
it('reloads search history and removes remotely deleted transactions',async()=>{
 mocks.all.mockResolvedValue([item('rent-old')]);
 const view=render(<TransactionList/>);
 await screen.findByText('rent-old');
 fireEvent.change(screen.getByRole('searchbox'),{target:{value:'rent'}});
 await waitFor(()=>expect(mocks.all).toHaveBeenCalledTimes(1));
 await screen.findByText('transactions.searchScope');
 mocks.all.mockResolvedValue([item("fresh")]);
 mocks.revision=1;mocks.transactions=[item('fresh')];
 mocks.fetch.mockResolvedValue({items:[item('fresh')],nextCursor:null,hasMore:false});
 view.rerender(<TransactionList auditRevision={1}/>);
 await waitFor(()=>expect(mocks.fetch).toHaveBeenCalledTimes(2));
 await waitFor(()=>expect(mocks.all).toHaveBeenCalledTimes(2));
 await waitFor(()=>expect(screen.queryByText('rent-old')).not.toBeInTheDocument());
});
it('restarts a cancelled search without getting stuck',async()=>{
 let resolve;mocks.all.mockReturnValue(new Promise(r=>{resolve=r;}));
 render(<TransactionList/>);await screen.findByText('rent-old');
 const search=screen.getByRole('searchbox');
 fireEvent.change(search,{target:{value:'rent'}});
 await waitFor(()=>expect(mocks.all).toHaveBeenCalledTimes(1));
 fireEvent.change(search,{target:{value:''}});
 await act(async()=>{resolve([item('rent-history')]);});
 mocks.all.mockResolvedValue([item('rent-history')]);
 fireEvent.change(search,{target:{value:'rent'}});
 await screen.findByText('rent-history');
 expect(mocks.all).toHaveBeenCalledTimes(2);
 expect(screen.queryByText('transactions.searchLoading')).not.toBeInTheDocument();
});

it('keeps the desktop editor open for historical search results',async()=>{
 mocks.all.mockResolvedValue([{...item('rent-history'),date:new Date(2026,0,1)}]);
 render(<TransactionList/>);await screen.findByText('rent-old');
 fireEvent.change(screen.getByRole('searchbox'),{target:{value:'rent'}});
 const row=await screen.findByRole('button',{name:/rent-history/});
 fireEvent.click(row);
 await waitFor(()=>expect(screen.getByRole('complementary',{name:'transactionModal.editTitle'})).toBeInTheDocument());
 expect(screen.getByText('rent-history')).toBeInTheDocument();
});
it('never reuses another account\'s history when revisions match', async () => {
  mocks.user={uid:'owner'};
  mocks.all.mockResolvedValue([item('rent-private')]);
  const view=render(<TransactionList/>);
  await screen.findByText('rent-old');
  fireEvent.change(screen.getByRole('searchbox'),{target:{value:'rent'}});
  await screen.findByText('rent-private');
  let resolveNew;
  mocks.all.mockReturnValue(new Promise(done=>{resolveNew=done;}));
  mocks.user={uid:'new-owner'};
  mocks.transactions=[];
  view.rerender(<TransactionList auditOwner="new-owner"/>);
  expect(screen.queryByText('rent-private')).not.toBeInTheDocument();
  await act(async()=>resolveNew([item('rent-new')]));
  await screen.findByText('rent-new');
  expect(mocks.all).toHaveBeenCalledTimes(2);
  mocks.user={uid:'owner'};
});
