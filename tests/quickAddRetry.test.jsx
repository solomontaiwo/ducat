import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import QuickAddForm from '../src/components/Dashboard/QuickAddForm.jsx';
const mocks=vi.hoisted(()=>({add:vi.fn(),t:k=>k,categories:[{value:'altro',label:'Altro'}],notification:{error:vi.fn()}}));
vi.mock('../src/context/UnifiedTransactionProvider.jsx',()=>({useUnifiedTransactions:()=>({addTransaction:mocks.add,isDemo:false,canAddMoreTransactions:true,transactions:[]})}));
vi.mock('../src/utils/categories.jsx',()=>({useCategories:()=>({visibleExpenseCategories:mocks.categories,visibleIncomeCategories:mocks.categories})}));
vi.mock('../src/utils/notificationUtils.jsx',()=>({useNotification:()=>mocks.notification}));
vi.mock('react-i18next',()=>({useTranslation:()=>({t:mocks.t})}));
afterEach(cleanup);
it('reuses the request ID after failure and rotates it after success',async()=>{
 mocks.add.mockResolvedValueOnce(false).mockResolvedValueOnce(true);
 render(<QuickAddForm/>);
 const amount=screen.getByLabelText('transactionModal.amount');
 fireEvent.change(amount,{target:{value:'12,50'}});
 fireEvent.submit(amount.closest('form'));
 await waitFor(()=>expect(mocks.add).toHaveBeenCalledTimes(1));
 await waitFor(()=>expect(screen.getByRole('button',{name:'dashboard.quickAddSubmit'})).not.toBeDisabled());
 fireEvent.submit(amount.closest('form'));
 await waitFor(()=>expect(mocks.add).toHaveBeenCalledTimes(2));
 expect(mocks.add.mock.calls[1][0].clientRequestId).toBe(mocks.add.mock.calls[0][0].clientRequestId);
 await waitFor(()=>expect(amount).toHaveValue(''));
 mocks.add.mockResolvedValueOnce(true);
 fireEvent.change(amount,{target:{value:'5'}});
 fireEvent.submit(amount.closest('form'));
 await waitFor(()=>expect(mocks.add).toHaveBeenCalledTimes(3));
 expect(mocks.add.mock.calls[2][0].clientRequestId).not.toBe(mocks.add.mock.calls[1][0].clientRequestId);
});
it('locks simultaneous submissions until the current request finishes', async () => {
  mocks.add.mockClear();
  let resolve;
  mocks.add.mockReturnValue(new Promise(done => { resolve = done; }));
  render(<QuickAddForm />);
  const amount = screen.getByLabelText('transactionModal.amount');
  fireEvent.change(amount, { target: { value: '5' } });
  fireEvent.submit(amount.closest('form'));
  fireEvent.submit(amount.closest('form'));
  expect(mocks.add).toHaveBeenCalledOnce();
  resolve(true);
  await waitFor(() => expect(amount).toHaveValue(''));
});
